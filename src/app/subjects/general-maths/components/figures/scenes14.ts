const rad = (deg: number) => (deg * Math.PI) / 180;
const r3 = (v: number) => Math.round(v * 1000) / 1000;

// `n` কোণবিশিষ্ট সুষম বহুভুজের শীর্ষ, কেন্দ্র `at` থেকে দূরত্ব `r`, প্রথম
// শীর্ষ `start` ডিগ্রিতে.
function regular(n: number, r: number, at: Pt = [0, 0], start = 90): Pt[] {
  return Array.from({ length: n }, (_, k) => {
    const a = rad(start + (360 * k) / n);
    return [r3(at[0] + r * Math.cos(a)), r3(at[1] + r * Math.sin(a))] as Pt;
  });
}

const shiftPt = (p: Pt, dx: number, dy: number): Pt => [
  r3(p[0] + dx),
  r3(p[1] + dy),
];

// একটি আকৃতির সবগুলো অংশ একসঙ্গে সরানো — কয়েকটি চিত্র এক সারিতে বসাতে.
function move(shapes: Shape[], dx: number, dy = 0): Shape[] {
  return shapes.map((s): Shape => {
    switch (s.t) {
      case "poly":
        return { ...s, pts: s.pts.map((p) => shiftPt(p, dx, dy)) };
      case "ring":
        return {
          ...s,
          outer: s.outer.map((p) => shiftPt(p, dx, dy)),
          inner: s.inner.map((p) => shiftPt(p, dx, dy)),
        };
      case "circle":
      case "arc":
      case "pt":
      case "note":
        return { ...s, at: shiftPt(s.at, dx, dy) };
      case "ang":
      case "sq":
        return {
          ...s,
          at: shiftPt(s.at, dx, dy),
          a: shiftPt(s.a, dx, dy),
          b: shiftPt(s.b, dx, dy),
        };
      case "seg":
      case "ray":
      case "len":
      case "dim":
      case "tick":
        return { ...s, a: shiftPt(s.a, dx, dy), b: shiftPt(s.b, dx, dy) };
      case "axes":
        return s;
    }
  });
}

// কেন্দ্র থেকে `deg` ডিগ্রি দিকে, দুই দিকে `len` দূরত্ব পর্যন্ত ড্যাশযুক্ত
// প্রতিসাম্য রেখা.
function mirror(at: Pt, deg: number, len: number): Shape {
  const c = r3(len * Math.cos(rad(deg)));
  const s = r3(len * Math.sin(rad(deg)));
  return {
    t: "seg",
    a: [at[0] - c, at[1] - s],
    b: [at[0] + c, at[1] + s],
    dash: true,
  };
}

